// **사용자에게 보이면 안 되는 말.**
//
// 이 제품은 기사가 참인지 거짓인지 말하지 않는다 (docs/product.md 2절).
// 지금까지 이 목록은 `apps/extension/tests/content.test.ts` 안에만 있었고,
// **미리 써 둔 문구를 검사하는 데**만 쓰였다. 그때는 그것으로 충분했다 — 화면에 뜨는
// 말이 전부 ChatKHU 가 미리 쓴 것이었기 때문이다.
//
// 리포트가 그 전제를 깬다. **심층 분석 리포트의 두 자리만은 실행 중에 생성된다**
// (전체 요약 한 문단, 주장별 "확인할 점" 한 줄). 미리 검수할 수가 없으므로
// **코드가 그 자리에서 본다.** 그래서 목록이 검사 파일에서 여기로 나왔다 —
// 검사와 런타임이 같은 목록을 봐야 한다.
//
// 걸리면 **그 글을 보여 주지 않는다.** 고치지 않는다 — 고치려 들면 그것도 우리가
// 쓰는 말이 되고, 어디까지 고쳤는지 아무도 모르게 된다.

/**
 * 단정으로 읽히는 말.
 *
 * 앞쪽 여섯은 "거짓이라고 말하는 쪽", 나머지는 **"맞다고 말하는 쪽"** 이다.
 * 둘 다 막는다 — 신호를 찾지 못한 것은 그 점에서 옳다고 확인한 것이 아니다.
 */
export const BANNED_WORDS: readonly string[] = [
  '가짜', '허위', '거짓', '사실이 아', '사실무근', '조작',
  '신뢰할 수 있', '믿을 만', '믿어도', '안전한 기사', '검증된',
  '문제없', '이상 없', '적절합', '타당합', '정확합', '충분합',
]

/** 그 글에 들어 있는 금지어. 없으면 빈 배열. */
export const bannedIn = (text: string): string[] =>
  BANNED_WORDS.filter((w) => text.includes(w))

/**
 * 실행 중에 생성된 글을 화면에 올려도 되는가.
 *
 * **고치지 않고 가린다.** 걸린 글은 통째로 버리고, 부르는 쪽이 미리 써 둔 문구로
 * 대신한다. 어설프게 고치면 그 글은 모델이 쓴 것도 우리가 쓴 것도 아닌 것이 된다.
 */
export function safeToShow(text: string): boolean {
  if (typeof text !== 'string' || text.trim().length === 0) return false
  // 꺾쇠가 든 글은 보여 주지 않는다. 우리는 마크업을 받지 않는다 —
  // 받아서 그리면 innerHTML 을 쓰지 않는다는 규칙이 돌아서 깨진다.
  if (/[<>]/.test(text)) return false
  return bannedIn(text).length === 0
}
